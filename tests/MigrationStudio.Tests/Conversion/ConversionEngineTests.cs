    [Fact]
    public async Task Engine_UsesMappedLowercaseSchemaAcrossExecutableArtifacts()
    {
        const string sourceSchema = "NREGA_SK";
        var inventory = CreateInventory();
        var remappedObjects = inventory.Objects.Select(item =>
            item.ObjectType == InventoryObjectType.Schema
                ? item with
                {
                    SourceName = sourceSchema,
                    QualifiedSourceName = $"[{sourceSchema}]"
                }
                : item with
                {
                    SourceSchema = sourceSchema,
                    QualifiedSourceName = $"[{sourceSchema}].[{item.SourceName}]",
                    SourceDefinition = item.SourceDefinition?
                        .Replace("[dbo]", $"[{sourceSchema}]", StringComparison.OrdinalIgnoreCase)
                }).ToList();
        var table = remappedObjects.Single(item => item.ObjectType == InventoryObjectType.Table);
        var function = Object(
            InventoryObjectType.Function,
            sourceSchema,
            "FnChkSau_DupAcc",
            100,
            null,
            $"CREATE FUNCTION [{sourceSchema}].[FnChkSau_DupAcc](@value nvarchar(100)) RETURNS bit AS BEGIN RETURN 0; END");
        var procedure = Object(
            InventoryObjectType.StoredProcedure,
            sourceSchema,
            "UpdateCustomer",
            101,
            null,
            $"CREATE PROCEDURE [{sourceSchema}].[UpdateCustomer] AS BEGIN UPDATE [{sourceSchema}].[Customer] SET [Name] = [Name]; END");
        var check = Object(
            InventoryObjectType.CheckConstraint,
            sourceSchema,
            "ChkSAU_DupAcc",
            102,
            table.Id);
        var unique = Object(
            InventoryObjectType.UniqueConstraint,
            sourceSchema,
            "UQ_Customer_Name",
            103,
            table.Id);
        var foreignKey = Object(
            InventoryObjectType.ForeignKey,
            sourceSchema,
            "FK_Customer_Parent",
            104,
            table.Id);
        remappedObjects.AddRange([function, procedure, check, unique, foreignKey]);

        var schema = remappedObjects.Single(item => item.ObjectType == InventoryObjectType.Schema);
        inventory = inventory with
        {
            Objects = remappedObjects,
            Schemas = [new SchemaInventory(schema, "dbo", remappedObjects.Count - 1, false, true)],
            Constraints = inventory.Constraints.Concat(
            [
                new ConstraintInventory(
                    check.Id, table.Id, ConstraintKind.Check, check.SourceName, [], null, [],
                    $"([{sourceSchema}].[FnChkSau_DupAcc]([Name])=(0))",
                    null, null, false, false, false, false, null, 0, null),
                new ConstraintInventory(
                    unique.Id, table.Id, ConstraintKind.Unique, unique.SourceName,
                    [new ConstraintColumn(1, "Name", false)], null, [], null,
                    null, null, false, false, false, false, null, 0, null),
                new ConstraintInventory(
                    foreignKey.Id, table.Id, ConstraintKind.ForeignKey, foreignKey.SourceName,
                    [new ConstraintColumn(1, "CustomerId", false)], table.Id,
                    [new ConstraintColumn(1, "CustomerId", false)], null,
                    "NO ACTION", "NO ACTION", false, false, false, false, null, 0, null)
            ]).ToArray(),
            Modules = inventory.Modules.Concat(
            [
                new ModuleInventory(
                    function.Id, ModuleKind.ScalarFunction, true, true, false, false, false, false,
                    null, false, false, false, false,
                    [
                        new ModuleParameterInventory(
                            0, string.Empty, "sys", "bit", 1, 1, 0, false, false, null, false, false),
                        new ModuleParameterInventory(
                            1, "@value", "sys", "nvarchar", 200, 0, 0, false, false, null, false, false)
                    ],
                    []),
                new ModuleInventory(
                    procedure.Id, ModuleKind.StoredProcedure, true, true, false, false, false, false,
                    null, false, false, false, false, [], [])
            ]).ToArray(),
            Dependencies = inventory.Dependencies.Concat(
            [
                new InventoryDependency(
                    function.Id,
                    table.Id,
                    DependencyKind.SqlExpression,
                    table.QualifiedSourceName,
                    true,
                    false),
                new InventoryDependency(
                    check.Id,
                    function.Id,
                    DependencyKind.SqlExpression,
                    function.QualifiedSourceName,
                    true,
                    false)
            ]).ToArray()
        };

        var run = await CreateEngine().ConvertAsync(
            inventory,
            new ConversionOptions(),
            null,
            CancellationToken.None);

        var executableSql = run.Artifacts
            .Where(item => !string.IsNullOrWhiteSpace(item.PostgreSqlDefinition))
            .Select(item => item.PostgreSqlDefinition)
            .ToArray();
        Assert.All(executableSql, sql =>
            Assert.DoesNotContain("\"NREGA_SK\"", sql, StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == schema.Id &&
            item.PostgreSqlDefinition.Contains("CREATE SCHEMA IF NOT EXISTS nrega_sk", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == table.Id &&
            item.PostgreSqlDefinition.Contains("CREATE TABLE nrega_sk.customer", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
    item.SourceObjectId == check.Id &&
    item.PostgreSqlDefinition.Contains(
        "NOT (nrega_sk.fnchksau_dupacc(name))",
        StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == unique.Id &&
            item.PostgreSqlDefinition.Contains("ALTER TABLE nrega_sk.customer", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == foreignKey.Id &&
            item.PostgreSqlDefinition.Contains("REFERENCES nrega_sk.customer", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Indexes &&
            item.PostgreSqlDefinition.Contains(" ON nrega_sk.customer ", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == function.Id &&
            item.PostgreSqlDefinition.Contains(
                "FUNCTION nrega_sk.fnchksau_dupacc",
                StringComparison.Ordinal));
        var functionArtifact = Assert.Single(run.Artifacts, item =>
            item.SourceObjectId == function.Id);
        var checkArtifact = Assert.Single(run.Artifacts, item =>
            item.SourceObjectId == check.Id);
        Assert.Equal(DeploymentPhase.PreDataFunctions, functionArtifact.DeploymentPhase);
        Assert.Equal("06_PreDataFunctions.sql", functionArtifact.ScriptFileName);
        Assert.Contains(function.Id, checkArtifact.Dependencies);
        var orderedArtifacts = run.Artifacts.ToList();
        Assert.True(
            orderedArtifacts.IndexOf(functionArtifact) <
            orderedArtifacts.IndexOf(checkArtifact));
        Assert.Contains(run.Artifacts, item =>
            item.SourceObjectId == procedure.Id &&
            item.PostgreSqlDefinition.Contains(
                "PROCEDURE nrega_sk.updatecustomer",
                StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.DeploymentPhase is DeploymentPhase.Views or DeploymentPhase.Triggers &&
            item.PostgreSqlDefinition.Contains("nrega_sk.", StringComparison.Ordinal));
        Assert.Contains(run.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Sequences &&
            item.PostgreSqlDefinition.Contains("nrega_sk.", StringComparison.Ordinal));
        Assert.All(run.Artifacts, artifact =>
            Assert.Equal(
                "nrega_sk",
                artifact.TargetObjectId.Schema));
    }

