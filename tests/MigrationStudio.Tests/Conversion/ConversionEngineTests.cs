    [Fact]
    public async Task Engine_ConvertsEveryIncludedObject_AndIsDeterministic()
    {
        var inventory = CreateInventory();
        var engine = CreateEngine();

        var first = await engine.ConvertAsync(inventory, new ConversionOptions(), null, CancellationToken.None);
        var second = await engine.ConvertAsync(inventory, new ConversionOptions(), null, CancellationToken.None);

        foreach (var source in inventory.Objects.Where(item => item.IsIncluded))
        {
            Assert.Contains(first.Artifacts, item => item.SourceObjectId == source.Id);
        }
        Assert.Equal(
            first.Artifacts.Select(item => item.ContentHash),
            second.Artifacts.Select(item => item.ContentHash));
        Assert.Equal(first.RunId, second.RunId);
        Assert.Contains(first.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Tables &&
            item.PostgreSqlDefinition.Contains("GENERATED BY DEFAULT AS IDENTITY", StringComparison.Ordinal));
        Assert.Contains(first.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Views &&
            item.PostgreSqlDefinition.Contains("LIMIT 5", StringComparison.Ordinal));
        Assert.Contains(first.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.PrimaryKeys &&
            item.PostgreSqlDefinition.Contains("PRIMARY KEY", StringComparison.Ordinal));
        Assert.Contains(first.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Indexes &&
            item.PostgreSqlDefinition.Contains("INCLUDE", StringComparison.Ordinal));
        Assert.Contains(first.Artifacts, item =>
            item.DeploymentPhase == DeploymentPhase.Sequences &&
            item.PostgreSqlDefinition.Contains("CACHE 50", StringComparison.Ordinal));
        Assert.Contains(first.Artifacts, item =>
            item.Classification == ConversionClassification.ManualConversion &&
            item.TargetObjectId.ObjectType == InventoryObjectType.Synonym.ToString());
        var triggerMapping = Assert.Single(first.IdentifierMappings, item =>
            item.SourceName == "TRG_DigiPay_TrainerDetailsHistory_Del");
        Assert.True(triggerMapping.AutoRecovered);
        Assert.NotNull(triggerMapping.SourceKey.TriggerKey);
        Assert.Equal(0, first.MappingSet.UnresolvedRequiredCount);
        Assert.All(first.MappingSet.Coverage, item =>
            Assert.Equal(item.IncludedCount, item.MappedCount));
    }

