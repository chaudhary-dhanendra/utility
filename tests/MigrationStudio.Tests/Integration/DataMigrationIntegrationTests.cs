            IsComputedPersisted: false,
            IsComputedDeterministic: null,
            IsSparse: false,
            IsColumnSet: false,
            IsRowGuidColumn: false,
            IsFileStream: false,
            GeneratedAlwaysType: 0,
            IsHidden: false,
            IsMasked: false,
            MaskingFunction: null,
            EncryptionType: null,
            EncryptionAlgorithm: null,
            ColumnEncryptionKey: null,
            XmlSchemaCollection: null,
            DefaultConstraintName: null,
            DefaultDefinition: null,
            RuleName: null,
            ExtendedProperties: []);

    private static SqlServerConnectionOptions ToOptions(SqlConnectionStringBuilder builder) =>
        new()
        {
            Server = builder.DataSource,
            Database = builder.InitialCatalog,
            AuthenticationMode = builder.IntegratedSecurity
                ? SqlServerAuthenticationMode.Windows
                : SqlServerAuthenticationMode.SqlServer,
            Username = builder.IntegratedSecurity ? null : builder.UserID,
            Password = builder.IntegratedSecurity ? null : builder.Password,
            Encrypt = builder.Encrypt,
            TrustServerCertificate = builder.TrustServerCertificate,
            ConnectionTimeoutSeconds = builder.ConnectTimeout,
            CommandTimeoutSeconds = 120
        };

    private static async Task ExecuteAsync(
        System.Data.Common.DbConnection connection,
        string sql)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync();
    }

    private sealed class TestPaths(string root) : IApplicationPaths
    {
        public string ApplicationDataDirectory { get; } = root;

        public string LogsDirectory { get; } = Path.Combine(root, "Logs");

        public string PluginsDirectory { get; } = Path.Combine(root, "Plugins");

        public string SettingsFilePath { get; } = Path.Combine(root, "settings.json");
    }
}

internal sealed class DataMigrationIntegrationFactAttribute : FactAttribute
{
    public DataMigrationIntegrationFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(
                Environment.GetEnvironmentVariable("MIGRATIONSTUDIO_SQLSERVER_INTEGRATION")) ||
            string.IsNullOrWhiteSpace(
                Environment.GetEnvironmentVariable("MIGRATIONSTUDIO_POSTGRES_INTEGRATION")))
        {
            Skip = "Set both database integration connection variables to run end-to-end data migration.";
        }
    }
}
