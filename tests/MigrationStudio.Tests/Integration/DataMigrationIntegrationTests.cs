            ParentObjectId: tableId,
            ColumnId: ordinal,
            OrdinalPosition: ordinal,
            Name: name,
            SystemTypeName: type,
            UserTypeName: type,
            TypeSchema: "sys",
            MaximumLength: length,
            Precision: precision,
            Scale: scale,
            Collation: null,
