public sealed record MigrationReportSummary(
    Guid ReportRunId,
    DateTimeOffset GeneratedAt,
    string ApplicationVersion,
    MigrationEndpointSummary Source,
    MigrationEndpointSummary Target,
    MigrationScopeMode Scope,
    IReadOnlyList<string> IncludedSchemas,
    int IncludedObjects,
    int ExcludedObjects,
    string SchemaConversionResult,
    string DataMigrationResult,
    string DeploymentResult,
    string ValidationResult,
    string OverallReadiness,
    int CriticalBlockers,
    int Warnings,
    int ManualReviews,
    int Unsupported,
    long RowsRead,
    long RowsWritten,
    long FailedRows,
    TimeSpan TotalDuration,
    double RowsPerSecond,
    TimeSpan DeploymentDuration,
    TimeSpan ValidationDuration)
{
    public bool RowsReconcile => RowsRead == RowsWritten + FailedRows;

    public long UnreconciledRows => RowsRead - RowsWritten - FailedRows;
}

