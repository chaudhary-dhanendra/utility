public sealed record SourceObjectReconciliation(
    InventoryObjectId SourceObjectId,
    string SourceObject,
    InventoryObjectType ObjectType,
    SourceObjectFinalStatus Status,
    string Reason,
    InventoryObjectId? EffectiveArtifactSourceObjectId);

public sealed record ObjectReconciliationSummary(
    int SelectedSourceObjects,
    int ConvertedDeployedValidated,
    int ConvertedValidationFailed,
    int ManualConversionRequired,
    int Unsupported,
    int ExcludedExplicitly,
    int NotApplicableToPostgreSql,
    int Unreconciled)
{
    public int ReconciledTotal =>
        ConvertedDeployedValidated +
        ConvertedValidationFailed +
        ManualConversionRequired +
        Unsupported +
        ExcludedExplicitly +
        NotApplicableToPostgreSql;

    public bool IsBalanced =>
        Unreconciled == 0 &&
        SelectedSourceObjects == ReconciledTotal;
}

