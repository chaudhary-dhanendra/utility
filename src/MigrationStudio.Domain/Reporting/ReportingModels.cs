public sealed record MigrationReportRequest
{
    public required InventorySnapshot Inventory { get; init; }

    public ConversionRun? Conversion { get; init; }

    public DataMigrationResult? DataMigration { get; init; }

    public DeploymentResult? Deployment { get; init; }

